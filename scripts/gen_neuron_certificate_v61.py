#!/usr/bin/env python3
"""Emit formal/neuron-gate-v1/NeuronGate/CertV61.lean: exact fixed-point (2^-200) encoding of the
V61-local logged selected/control effects, so Lean recomputes ctl_max, p-numerator and `supported`
from raw logged numbers. Slice: neuron-gate-formal-v1. Fails closed on any mismatch."""
import json, sys
from fractions import Fraction
R = "docs/research/astral-self-modeling/v61-local-run/results/out_v61_local.json"
S = 200
def fx(x):
    v = Fraction(x) * 2**S
    assert v.denominator == 1, "not exactly representable"
    return int(v)
summ = json.load(open(R))
log = [json.loads(l) for l in open(R + ".jsonl")]
def vals(call):
    return [d["value"] for d in log if d["call"] == call and isinstance(d.get("value"), dict)]
tasks = [("t0", "swap_effect", "t0_all_position_swap"), ("l", "swap_effect_last", "l_last_position_swap"),
         ("p", "patch_last", "p_donor_patch")]
out = ["import NeuronGate.Gate", "", "/-! GENERATED by scripts/gen_neuron_certificate_v61.py -- do not edit. Slice neuron-gate-formal-v1.",
       "Exact 2^-200 fixed-point copy of logged V61-local effects; Lean recomputes the verdict. -/",
       "namespace CertV61", "def one : Int := 1", ""]
for tag, call, key in tasks:
    v = vals(call)
    sel, ctl = v[0], v[1:101]
    assert len(ctl) == 100
    rep = summ[key]
    for k in ("sing", "plur", "all"):
        assert sel[k] == rep["selected"][k]
        assert max(c[k] for c in ctl) == rep["ctl_max"][k]
    out.append(f"def {tag}Sel : Eff := ⟨{fx(sel['sing'])}, {fx(sel['plur'])}, {fx(sel['all'])}⟩")
    out.append(f"def {tag}CtlMax : Eff := ⟨{fx(rep['ctl_max']['sing'])}, {fx(rep['ctl_max']['plur'])}, {fx(rep['ctl_max']['all'])}⟩")
    for k in ("sing", "plur", "all"):
        out.append(f"def {tag}Ctl{k.capitalize()} : List Int := [{', '.join(str(fx(c[k])) for c in ctl)}]")
    out.append("")
floor = fx(0.1)
out += [f"def floor : Int := {floor}", ""]
for tag, _, _ in tasks:
    S_ = tag
    out += [f"/-- recomputed max of the 100 logged controls equals the reported ctl_max -/",
            f"theorem {tag}_max_sing : {tag}CtlSing.foldl max ({tag}CtlSing.head!) = {tag}CtlMax.sing := by decide +kernel",
            f"theorem {tag}_max_plur : {tag}CtlPlur.foldl max ({tag}CtlPlur.head!) = {tag}CtlMax.plur := by decide +kernel",
            f"theorem {tag}_max_all : {tag}CtlAll.foldl max ({tag}CtlAll.head!) = {tag}CtlMax.all := by decide +kernel",
            f"theorem {tag}_len : {tag}CtlAll.length = 100 := by decide +kernel",
            f"/-- the gate verdict, from the recomputed maxima -/",
            f"theorem {tag}_supported : supported {tag}Sel {tag}CtlMax floor := by decide +kernel",
            f"/-- selected beats every one of the 100 logged controls on `all`: exact p = 1/101 -/",
            f"theorem {tag}_p : pNum ({tag}Sel.all) {tag}CtlAll = 1 ∧ pDen {tag}CtlAll = 101 := by decide +kernel", ""]
out.append("end CertV61")
open("formal/neuron-gate-v1/NeuronGate/CertV61.lean", "w").write("\n".join(out) + "\n")
print("ok")
